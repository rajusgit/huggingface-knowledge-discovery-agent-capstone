"""Regenerate config/sources.yaml from config/corpus.yaml.

  uv run python standalone-scripts/build_registry.py [--no-url-check]

For each repo: latest release tag (or default branch) -> pinned commit SHA, repo license from the
GitHub API (anything outside ingest.allowed_licenses stays `pending_review`), deterministic page
selection, and a check that every citation URL actually resolves (broken ones are dropped).
"""
import argparse
import json
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src import config, corpus, ingest  # noqa: E402


def api(path: str):
    return json.loads(ingest._get(config.settings.ingest.github_api + path, accept="application/vnd.github+json"))


p = argparse.ArgumentParser()
p.add_argument("--no-url-check", action="store_true")
args = p.parse_args()

cfg = config.settings.ingest
spec = yaml.safe_load((config.ROOT / "config" / "corpus.yaml").read_text())["repos"]
entries, report = [], []
for r in spec:
    repo = r["repo"]
    try:
        tag = api(f"/repos/{repo}/releases/latest")["tag_name"]
    except Exception:
        tag = api(f"/repos/{repo}")["default_branch"]
    sha = ingest._get(f"{cfg.github_api}/repos/{repo}/commits/{tag}", accept="application/vnd.github.sha").strip()
    license_id = (api(f"/repos/{repo}/license").get("license") or {}).get("spdx_id")
    tree = api(f"/repos/{repo}/git/trees/{sha}?recursive=1")
    if tree.get("truncated"):
        sys.exit(f"{repo}: git tree truncated; narrow the root")
    paths = corpus.select_pages(tree["tree"], root=r["root"], exclude=r.get("exclude", []),
                                min_bytes=cfg.min_page_bytes, max_bytes=cfg.max_page_bytes, max_pages=r["max_pages"],
                                priority=r.get("priority"))
    for name in corpus.missing_priority(tree["tree"], r["root"], r.get("priority", [])):
        print(f"  note: priority page {name!r} not found in {repo} @ {tag}; skipped")
    new = corpus.build_entries(name=r["name"], repo=repo, tag=tag, sha=sha, license_id=license_id,
                               url_base=r["url_base"], category=r["category"], allowed=cfg.allowed_licenses,
                               paths=paths, root=r["root"], suffix=r.get("url_suffix", ""))
    report.append(f"{r['name']:22} {tag:10} {sha[:8]} {license_id}  {len(new)} pages")
    entries += new

if not args.no_url_check:
    broken, unverified = ingest.check_urls_detail([e["canonical_url"] for e in entries])
    broken = set(broken)
    if unverified:
        print(f"warning: kept {len(unverified)} pages whose URL could not be verified (rate-limited/unreachable)")
    for e in entries:
        if e["canonical_url"] in broken:
            print("dropping (URL does not resolve):", e["canonical_url"])
    entries = [e for e in entries if e["canonical_url"] not in broken]

header = (f"# GENERATED by standalone-scripts/build_registry.py from config/corpus.yaml on "
          f"{datetime.now(timezone.utc).strftime('%Y-%m-%d')}. Edit corpus.yaml, not this file.\n"
          "# permitted_use: pending_review | index_text | reference_only | rejected\n")
(config.ROOT / cfg.sources_file).write_text(header + yaml.safe_dump({"sources": entries}, sort_keys=False, width=120))
print("\n".join(report))
print(f"wrote {len(entries)} sources to {cfg.sources_file}; "
      f"{sum(e['permitted_use'] == 'index_text' for e in entries)} approved for indexing")
